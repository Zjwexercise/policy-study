def apply_fixes():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    
    fixed_count = 0
    for (wb_id, q_num), new_stem in STEM_FIXES.items():
        # 1. 更新分卷题目
        c.execute("""
            UPDATE questions 
            SET stem = ? 
            WHERE workbook_id = ? AND question_num = ?
        """, (new_stem, wb_id, q_num))
        
        # 2. 更新合集 (workbook_id = 49) 对应题目
        master_q_num = (wb_id - 41) * 33 + q_num
        c.execute("""
            UPDATE questions 
            SET stem = ? 
            WHERE workbook_id = 49 AND question_num = ?
        """, (new_stem, master_q_num))
        
        fixed_count += 1
        print(f"Fixed: WB{wb_id} Q{q_num} (Master Q{master_q_num}) -> {new_stem[:40]}...")
        
    conn.commit()
    conn.close()
    print(f"\n🎉 成功修复 {fixed_count} 道肖8题目的题干内容！")

if __name__ == "__main__":
    apply_fixes()
